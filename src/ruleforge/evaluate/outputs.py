class TokenReadoutError(SamplingDesignError):
    """A campaign root, ruleset or tokenizer the readout cannot read as the ledger defines it."""


@dataclass(frozen=True)
class RawOutput:
    """One returned component output, with the ledger row that vouches for it."""

    decoder_draw_id: int
    record: AttemptRecord
    component: ComponentRecord
    row: Mapping[str, Any]

    @property
    def scenario_id(self) -> str:
        return self.record.scenario_id

    @property
    def component_id(self) -> str:
        return self.component.component_id

    @property
    def kind(self) -> str:
        return component_kind(self.component_id)

    @property
    def raw_response(self) -> str:
        return self.row.get("raw_response") or ""

    @property
    def finish_reason(self) -> Optional[str]:
        return self.row.get("finish_reason")

    @property
    def first_attempt(self) -> bool:
        """Generated by the first semantic attempt of its (scenario, draw) that consumed one."""
        return self.record.semantic_attempt_id == 0 and self.record.consumes_attempt

    def outcome(self) -> GenerationOutcome:
        """Return the generation outcome the runner classified, rebuilt from the raw row."""
        summaries = self.row.get(REASONING_SUMMARIES_KEY)
        return GenerationOutcome(
            text=self.row.get("completion"),
            raw_response=self.row.get("raw_response"),
            finish_reason=self.finish_reason,
            error=self.row.get("error"),
            reasoning_summaries=None if summaries is None else tuple(summaries),
            reasoning=self.row.get(REASONING_KEY),
        )


def raw_rows(path: Path) -> Iterator[Optional[dict[str, Any]]]:
    """Return a draw's raw rows in written order, None for a torn final line; a bad line anywhere else is refused."""
    if not path.is_file():
        return
    with path.open("rb") as handle:
        for number, line in enumerate(handle, start=1):
            if not line.strip():
                continue
            try:
                yield json.loads(line)
            except (json.JSONDecodeError, UnicodeDecodeError) as error:
                if line.endswith(b"\n"):
                    raise TokenReadoutError(f"{path} line {number} is not a JSON row ({error})") from error
                yield None


def draw_outputs(ledger: DrawLedger, state: LedgerState) -> tuple[list[RawOutput], int]:
    """Return a draw's outputs, each checked against its ledger row, and how many raw rows no row vouches for."""
    records_by_key = {(r.scenario_id, r.semantic_attempt_id, r.request_block_id): r for r in state.records}
    outputs: list[RawOutput] = []
    seen: set[tuple[str, int, str, str]] = set()
    orphans = 0
    for row in raw_rows(ledger.raw_path):
        key = None if row is None else raw_row_key(row)
        record = None if key is None else records_by_key.get(key)
        if record is None:
            orphans += 1
            continue
        where = f"{ledger.raw_path} {key[0][:12]}/attempt {key[1]}/{row['component_id']}"
        components = {component.component_id: component for component in record.components}
        component = components.get(row["component_id"])
        if component is None or (*key, component.component_id) in seen:
            raise TokenReadoutError(f"{where}: no component of its ledger row, or a second raw row for one")
        digest = raw_output_sha256(row.get("raw_response"))
        if digest != component.raw_output_sha256 or row.get("raw_output_sha256") != digest:
            raise TokenReadoutError(f"{where}: the raw output does not hash to the digest its ledger row vouches for")
        if row.get("finish_reason") != component.finish_reason:
            raise TokenReadoutError(
                f"{where}: the raw row's finish reason {row.get('finish_reason')!r} is not the "
                f"{component.finish_reason!r} its ledger row records"
            )
        seen.add((*key, component.component_id))
        outputs.append(RawOutput(ledger.decoder_draw_id, record, component, row))
    vouched = {
        (record.scenario_id, record.semantic_attempt_id, record.request_block_id, component.component_id)
        for record in state.records
        for component in record.components
        if component.raw_output_sha256 is not None
    }
    missing = sorted(vouched - seen)
    if missing:
        first = missing[0]
        raise TokenReadoutError(
            f"{ledger.raw_path}: {len(missing)} output(s) its ledger vouches for have no raw row (first "
            f"{first[0][:12]}/attempt {first[1]}/{first[3]}); every population would silently lose them"
        )
    return outputs, orphans


def load_rules(path: Path | str, condition: ConditionSpec) -> list[dict[str, Any]]:
    """The ruleset a condition judged, refused unless the file's digest is the condition's."""
    actual = sha256_file(path)
    if actual != condition.rule_set_sha256:
        raise TokenReadoutError(
            f"{path} has SHA-256 {actual[:12]}...; condition {condition.condition_id!r} judged ruleset "
            f"{condition.rule_set_sha256[:12]}..., and its outputs are validated against that one"
        )
    return load_jsonl_records(path)


@dataclass(frozen=True)
class CampaignRoot:
    """A campaign root as the readout reads it: its manifests and registered conditions."""

    root: Path
    manifest: dict[str, Any]
    scenario_manifest: ScenarioManifest
    conditions: dict[str, ConditionSpec]
    manifest_sha256: str

    @classmethod
    def open(cls, root: Path | str) -> "CampaignRoot":
        base = Path(root)
        manifest, manifest_sha256 = read_sampling_manifest(base / SAMPLING_MANIFEST_FNAME)
        scenario_manifest = ScenarioManifest.load(base / SCENARIO_MANIFEST_FNAME)
        if scenario_manifest.manifest_sha256 != manifest["scenario_manifest_sha256"]:
            raise TokenReadoutError(f"{base}: the scenario manifest is not the one the campaign manifest froze")
        return cls(base, manifest, scenario_manifest, load_conditions(base), manifest_sha256)

    @property
    def campaign_id(self) -> str:
        return str(self.manifest["campaign_id"])

    @property
    def n_draws(self) -> int:
        return int(self.manifest["expected_decoder_draws"])

    def condition(self, condition_id: str) -> ConditionSpec:
        if condition_id not in self.conditions:
            raise TokenReadoutError(f"{self.root} registers no condition {condition_id!r}")
        return self.conditions[condition_id]

    def ledgers(self, condition_id: str) -> list[DrawLedger]:
        """The condition's draw ledgers that exist, in draw order."""
        ledgers = [
            DrawLedger(
                self.root / condition_id / draw_dirname(draw),
                campaign_id=self.campaign_id,
                condition_id=condition_id,
                decoder_draw_id=draw,
            )
            for draw in range(self.n_draws)
        ]
        return [ledger for ledger in ledgers if ledger.ledger_path.is_file()]

    def draws(self, condition_id: str) -> Iterator[tuple[DrawLedger, LedgerState, list[RawOutput], int]]:
        """Each run draw of the condition: its ledger, its state, its returned outputs and its unvouched raw rows."""
        self.condition(condition_id)
        for ledger in self.ledgers(condition_id):
            state = ledger.load()
            outputs, orphans = draw_outputs(ledger, state)
            yield ledger, state, outputs, orphans

    def outputs(self, condition_id: str) -> tuple[list[RawOutput], int]:
        """Every returned output of the condition, draw by draw, and the unvouched raw rows."""
        outputs: list[RawOutput] = []
        orphans = 0
        for _, _, found, dropped in self.draws(condition_id):
            outputs.extend(found)
            orphans += dropped
        return outputs, orphans

    def record(self) -> dict[str, Any]:
        """Return what names this root's contents by digest; ``content_sha256`` leaves out the path, so a copy keeps
        it."""
        gate = campaign_completion(self.root, write=False)
        conditions = {}
        for condition_id, condition in sorted(self.conditions.items()):
            draws = {}
            for draw in range(self.n_draws):
                directory = self.root / condition_id / draw_dirname(draw)
                draws[str(draw)] = {
                    "state": gate["conditions"][condition_id]["draws"][str(draw)]["state"],
                    **{
                        name: sha256_file(directory / name) if (directory / name).is_file() else None
                        for name in (LEDGER_FNAME, RAW_OUTPUTS_FNAME)
                    },
                }
            conditions[condition_id] = {
                "fingerprint": condition.fingerprint,
                "evaluation_mode": condition.evaluation_mode,
                "draws": draws,
            }
        content = {
            "campaign_id": self.campaign_id,
            "campaign_mode": self.manifest["campaign_mode"],
            "sampling_manifest_sha256": self.manifest_sha256,
            "scenario_manifest_sha256": self.scenario_manifest.manifest_sha256,
            "scenario_source_name": self.scenario_manifest.source_name,
            "scenario_source_sha256": self.scenario_manifest.source_sha256,
            "scenarios": self.scenario_manifest.record_count,
            "decoder_draws": self.n_draws,
            "state": gate["state"],
            "conditions": conditions,
        }
        return {"root": artifact_uri_or_path(self.root), **content, "content_sha256": canonical_digest(content)}
